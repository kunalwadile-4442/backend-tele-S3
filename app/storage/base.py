from abc import ABC, abstractmethod
from typing import BinaryIO

class StorageProvider(ABC):
    @abstractmethod
    async def upload_file(self, stream: BinaryIO, filename: str, mime_type: str, caption: str | None = None) -> str: ...
    @abstractmethod
    async def download_file(self, reference: str): ...
    @abstractmethod
    async def delete_file(self, reference: str) -> None: ...
    @abstractmethod
    async def check_health(self) -> bool: ...
